import { NextResponse } from "next/server";
import { generateRandomGraph, type GraphGenerationConfig } from "@/lib/rpaFrameworkV4";
import { makeSessionId, rpaSessions } from "@/lib/rpaServerState";
import { responseMeta } from "@/lib/rpaApi";

export async function POST(request: Request) {
  const started = Date.now();
  try {
    const input = await request.json() as Partial<GraphGenerationConfig>;
    const config: GraphGenerationConfig = { targetNodes: input.targetNodes ?? 12, userMaxNodes: input.userMaxNodes ?? 24, systemCap: Math.min(80, input.systemCap ?? 80), density: input.density ?? 0.24, direction: input.direction ?? "bidirectional", topology: input.topology ?? "connected", seed: input.seed ?? 271828, ensureConnected: input.ensureConnected ?? true, nodeWeightDistribution: input.nodeWeightDistribution ?? "lognormal", edgeWeightDistribution: input.edgeWeightDistribution ?? "uniform", domain: input.domain ?? "road" };
    const graph = generateRandomGraph(config), id = makeSessionId(graph.seed), now = new Date().toISOString();
    rpaSessions.set(id, { id, graph, suite: null, observations: [], history: [], predictions: [], outcomes: [], residuals: [], trajectories: [], createdAt: now, updatedAt: now });
    return NextResponse.json({ session_id: id, graph, meta: responseMeta(graph, null, started, graph.seed, ["synthetic graph generator", "hidden destination not generated by this endpoint"]) });
  } catch (error) { return NextResponse.json({ error: error instanceof Error ? error.message : "graph build failed" }, { status: 400 }); }
}
